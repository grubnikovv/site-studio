"""Оценка выгоды и подвохов без нейросети: скидка к рынку, расчёт прибыли, тревожные слова и признаки."""
import re

# Слова в описании, на которые перекуп смотрит в первую очередь.
RED = {
    r"\bдтп\b|после аварии|бит(ая|ый)|удар": "упоминается ДТП",
    r"не на ходу|не заводится|требует ремонта|под восстановление|на запчасти": "не на ходу / под ремонт",
    r"залог|кредит|банк": "возможен залог или кредит",
    r"арест|запрет на рег|ограничени": "ограничения на регистрацию",
    r"дубликат": "дубликат ПТС",
    r"такси|каршеринг|аренд": "работала в такси / аренде",
    r"без документов|нет птс|утерян|не растаможен|на учете не стоит|снята с учета|утиль": "проблемы с документами",
    r"стук|пинки|дым|жор масла|ест масло|троит|капиталк|мотор под замену|двигатель под замену": "проблемы с мотором / коробкой",
    r"гнил|ржав|коррози|сквозн": "ржавчина",
    r"перевертыш|утопленник|после пожара|тотал": "тяжёлая история кузова",
    r"скручен|подмотан": "пробег под вопросом",
    r"без торга|торга не будет": "без торга",
}
GOOD = {r"срочно|быстрая продажа|переезд|уезжаю": "срочная продажа — можно торговаться", r"торг": "уместен торг",
        r"один владелец|1 владелец": "один владелец", r"сервисн.. книжк|обслуживал.. у дилера": "есть история обслуживания"}

PREP = 15000      # подготовка к продаже: мойка, химчистка, полировка, мелочи
FEES = 5000       # оформление, объявления
SELL_K = 0.97     # продаём чуть ниже рынка, чтобы уйти быстро


def flags(d):
    low = (d.get("text") or "").lower()
    red = sorted({v for k, v in RED.items() if re.search(k, low)})
    good = sorted({v for k, v in GOOD.items() if re.search(k, low)})
    if d.get("damaged"): red.append("отмечено «требует ремонта / битая»")
    if d.get("docs") is False: red.append("нет документов")
    if (d.get("owners") or 0) >= 4: red.append("4+ владельца по ПТС")
    if d.get("no_rf_km"): good.append("без пробега по РФ")
    for r in d.get("vin_report", []):
        if r["status"] in ("caution", "error", "warning", "failed"):
            red.append("отчёт Дрома: " + r["value"])
        elif r["status"] == "checked":
            good.append("отчёт Дрома: " + r["value"])
    return red, good


def profit(d, repair=0):
    """Ожидаемая прибыль при перепродаже по рыночной цене Дрома."""
    if not d.get("market") or not d.get("price"):
        return None
    sell = int(d["market"] * SELL_K)
    reserve = int(d["price"] * 0.02)  # запас на мелкие сюрпризы
    return {"buy": d["price"], "sell": sell, "costs": PREP + FEES + reserve + repair, "repair": repair,
            "profit": sell - d["price"] - PREP - FEES - reserve - repair,
            "discount": round(100 * (d["market"] - d["price"]) / d["market"], 1)}
